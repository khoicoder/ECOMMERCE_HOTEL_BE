package com.example.BE.enums;

public enum HotelType {
    CITY,
    RESORT,
    FLOATING,
    MOTEL

}
//Khách sạn thành phố (City hotel): Xây dựng tại các đô thị, phục vụ khách du lịch, công vụ và thương gia.
// Khách sạn nghỉ dưỡng (Resort hotel): Quần thể biệt thự, bungalow nằm ở khu vực có cảnh quan thiên nhiên đẹp (bãi biển, rừng núi).
// Khách sạn nổi (Floating hotel): Các cơ sở lưu trú nổi trên mặt nước, di chuyển được.
// Khách sạn bên đường (Motel): Nằm ven các quốc lộ, đường cao tốc, phục vụ khách đi đường.